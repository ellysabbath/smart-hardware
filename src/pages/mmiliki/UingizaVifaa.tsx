// ============================================================
// Historia ya Uingizaji
// ============================================================
function Historia({ uingizaji }: { uingizaji: UingizajiVifaa[] }) {
  const { t } = usePageText()
  const [query, setQuery] = useState('')
  const [haliFilter, setHaliFilter] = useState<'zote' | HaliUingizaji>('zote')

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase()

    return [...uingizaji]
      .filter((item) => {
        const textMatches = !q || (
          item.id.toLowerCase().includes(q) ||
          item.dukaJina.toLowerCase().includes(q) ||
          item.aliyeingiza.toLowerCase().includes(q) ||
          item.bidhaa.some((b) =>
            b.jina.toLowerCase().includes(q) ||
            b.sku.toLowerCase().includes(q)
          )
        )

        return textMatches && (haliFilter === 'zote' || item.hali === haliFilter)
      })
      .sort((a, b) => b.tarehe.localeCompare(a.tarehe))
  }, [uingizaji, query, haliFilter])

  const statusLabel = (hali: HaliUingizaji) => {
    if (hali === 'inasubiri') return t.pending
    if (hali === 'imepokelewa') return t.received
    return t.rejected
  }

  return (
    <div className="bg-white rounded-2xl border border-slate-200 p-4 md:p-5 space-y-4">
      <div className="flex flex-col md:flex-row gap-3">
        <div className="relative flex-1">
          <Search size={16} className="absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
          <input
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder={t.searchPlaceholder}
            className="w-full pl-9 pr-3 py-2.5 rounded-lg border border-slate-200 text-sm outline-none focus:border-brand-500"
          />
        </div>

        <select
          value={haliFilter}
          onChange={(e) => setHaliFilter(e.target.value as 'zote' | HaliUingizaji)}
          className="px-3 py-2.5 rounded-lg border border-slate-200 bg-white text-sm outline-none focus:border-brand-500"
        >
          <option value="zote">{t.all}</option>
          <option value="inasubiri">{t.pending}</option>
          <option value="imepokelewa">{t.received}</option>
          <option value="imekataliwa">{t.rejected}</option>
        </select>
      </div>

      {filtered.length === 0 ? (
        <div className="py-12 text-center text-sm text-slate-500">
          <Package size={30} className="mx-auto mb-2 text-slate-300" />
          {t.noMatchingEntries}
        </div>
      ) : (
        <div className="space-y-3">
          {filtered.map((item) => {
            const meta = HALI_META[item.hali]
            const StatusIcon = meta.Icon

            return (
              <div key={item.id} className="border border-slate-200 rounded-xl p-3 md:p-4">
                <div className="flex flex-col sm:flex-row sm:items-start sm:justify-between gap-3">
                  <div className="min-w-0">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-sm font-bold text-slate-800">{item.id}</span>
                      <span className="text-[10px] px-2 py-1 rounded-full bg-slate-100 text-slate-600">
                        {item.aina === 'moja' ? t.single : t.bulk}
                      </span>
                    </div>
                    <div className="text-sm font-semibold text-slate-800 mt-1">{item.dukaJina}</div>
                    <div className="text-xs text-slate-500 mt-1">
                      {item.tarehe} · {item.aliyeingiza}
                    </div>
                  </div>

                  <div className={`inline-flex items-center gap-1.5 text-xs font-semibold ${meta.tone}`}>
                    <StatusIcon size={15} />
                    {statusLabel(item.hali)}
                  </div>
                </div>

                <div className="mt-3 grid grid-cols-2 md:grid-cols-3 gap-2">
                  <div className="bg-slate-50 rounded-lg p-2.5">
                    <div className="text-[10px] text-slate-500">{t.products}</div>
                    <div className="text-sm font-bold text-slate-800">
                      {item.bidhaa.length} {t.productsCount}
                    </div>
                  </div>

                  <div className="bg-slate-50 rounded-lg p-2.5">
                    <div className="text-[10px] text-slate-500">{t.totalProducts}</div>
                    <div className="text-sm font-bold text-slate-800">
                      {item.jumlaBidhaa.toLocaleString()}
                    </div>
                  </div>

                  <div className="bg-slate-50 rounded-lg p-2.5 col-span-2 md:col-span-1">
                    <div className="text-[10px] text-slate-500">{t.valuePurchase}</div>
                    <div className="text-sm font-bold text-brand-700">
                      Tsh {item.jumlaThamani.toLocaleString()}
                    </div>
                  </div>
                </div>

                <div className="mt-3 border-t border-slate-100 pt-3 space-y-2">
                  {item.bidhaa.map((bidhaa, index) => {
                    const Icon = iconForKundi(bidhaa.kundi)

                    return (
                      <div key={`${item.id}-${index}`} className="flex items-center gap-2">
                        <div className="w-8 h-8 rounded-lg bg-slate-50 border border-slate-100 grid place-items-center text-slate-500 shrink-0 overflow-hidden">
                          {bidhaa.pichaUrl ? (
                            <img src={bidhaa.pichaUrl} alt="" className="w-full h-full object-cover" />
                          ) : (
                            <Icon size={15} />
                          )}
                        </div>
                        <div className="flex-1 min-w-0">
                          <div className="text-xs font-semibold text-slate-800 truncate">{bidhaa.jina}</div>
                          <div className="text-[10px] text-slate-500 truncate">
                            {bidhaa.sku} · {bidhaa.stoki} {bidhaa.uom}
                          </div>
                        </div>
                        <div className="text-xs font-semibold text-slate-700 whitespace-nowrap">
                          Tsh {(bidhaa.stoki * bidhaa.beiUnunuzi).toLocaleString()}
                        </div>
                      </div>
                    )
                  })}
                </div>

                {item.maelezo && (
                  <div className="mt-3 text-xs text-slate-500 bg-slate-50 rounded-lg p-2.5">
                    {item.maelezo}
                  </div>
                )}

                {item.aliyepokea && (
                  <div className="mt-3 text-xs text-emerald-700">
                    {t.receivedBy}: <strong>{item.aliyepokea}</strong>
                    {item.tareheKupokea ? ` · ${item.tareheKupokea}` : ''}
                  </div>
                )}
              </div>
            )
          })}
        </div>
      )}
    </div>
  )
}

// Picha Upload
// ============================================================
function PichaUpload({
  value, onChange,
}: {
  value?: string
  onChange: (dataUrl: string | undefined) => void
}) {
  const { t } = usePageText()
  const inputRef = useRef<HTMLInputElement>(null)
  const [alert, setAlert] = useState<{ title: string; message: string; tone: 'danger' | 'warning' } | null>(null)

  const compressAndSet = (file: File) => {
    const reader = new FileReader()

    reader.onload = () => {
      const img = new Image()

      img.onload = () => {
        const MAX = 800
        let { width, height } = img

        if (width > height && width > MAX) {
          height = Math.round((height * MAX) / width)
          width = MAX
        } else if (height > MAX) {
          width = Math.round((width * MAX) / height)
          height = MAX
        }

        const canvas = document.createElement('canvas')
        canvas.width = width
        canvas.height = height
        const ctx = canvas.getContext('2d')

        if (!ctx) {
          setAlert({
            title: t.imageProcessingError,
            message: t.browserImageError,
            tone: 'danger',
          })
          return
        }

        ctx.drawImage(img, 0, 0, width, height)

        let dataUrl = canvas.toDataURL('image/jpeg', 0.85)
        let quality = 0.85

        while (dataUrl.length > 800_000 && quality > 0.3) {
          quality -= 0.1
          dataUrl = canvas.toDataURL('image/jpeg', quality)
        }

        onChange(dataUrl)
      }

      img.onerror = () => {
        setAlert({
          title: t.imageReadError,
          message: t.invalidImage,
          tone: 'danger',
        })
      }

      img.src = reader.result as string
    }

    reader.onerror = () => {
      setAlert({
        title: t.fileReadError,
        message: t.fileReadAgain,
        tone: 'danger',
      })
    }

    reader.readAsDataURL(file)
  }

  const handleFile = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0]
    if (!file) return

    if (!file.type.startsWith('image/')) {
      setAlert({
        title: t.notImage,
        message: t.chooseValidImage,
        tone: 'warning',
      })
      return
    }

    compressAndSet(file)
    e.target.value = ''
  }

  return (
    <div>
      <label className="text-sm font-medium">{t.productImage}</label>

      <div className="mt-1.5 flex items-center gap-3">
        <div className="w-20 h-20 rounded-xl bg-slate-50 border border-slate-200 grid place-items-center overflow-hidden shrink-0">
          {value ? (
            <img src={value} alt="product" className="w-full h-full object-cover" />
          ) : (
            <ImageIcon size={24} className="text-slate-300" />
          )}
        </div>

        <div className="flex-1 min-w-0 space-y-1.5">
          <input
            ref={inputRef}
            type="file"
            accept="image/*"
            onChange={handleFile}
            className="hidden"
          />

          <div className="flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={() => inputRef.current?.click()}
              className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-100 hover:bg-slate-200 text-sm font-medium"
            >
              <Upload size={14} /> {value ? t.changeImage : t.uploadImage}
            </button>

            {value && (
              <button
                type="button"
                onClick={() => onChange(undefined)}
                className="inline-flex items-center gap-1 px-2 py-1 rounded-md text-xs text-red-600 hover:bg-red-50"
              >
                <X size={12} /> {t.remove}
              </button>
            )}
          </div>

          <div className="text-[10px] text-slate-500 flex items-center gap-1">
            <AlertTriangle size={10} className="text-amber-500" />
            {t.imageNote}
          </div>
        </div>
      </div>

      <AlertModal
        open={!!alert}
        title={alert?.title ?? ''}
        message={alert?.message ?? ''}
        tone={alert?.tone ?? 'danger'}
        onClose={() => setAlert(null)}
      />
    </div>
  )
}

